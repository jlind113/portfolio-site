export function getPuzzlesByDifficulty(
	difficulty: Difficulty,
): PuzzleDefinition[] {
	return PUZZLES.filter((puzzle) => puzzle.difficulty === difficulty);
}

export function getPuzzleById(id: string): PuzzleDefinition | undefined {
	return PUZZLES.find((puzzle) => puzzle.id === id);
}

export function getRandomPuzzle(
	difficulty: Difficulty,
	excludeId?: string,
): PuzzleDefinition {
	const pool = getPuzzlesByDifficulty(difficulty);
	const candidates =
		excludeId && pool.length > 1
			? pool.filter((puzzle) => puzzle.id !== excludeId)
			: pool;
	const index = Math.floor(Math.random() * candidates.length);
	return candidates[index];
}
